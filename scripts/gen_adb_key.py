#!/usr/bin/env python3
"""Generate the RSA key pair that ADB uses to authenticate this iOS client.

The generated private key is embedded in the Swift source in PKCS#1 DER form.
The public key is encoded in Android's custom RSAPublicKey binary format
(base64 + comment + NUL), exactly like the .pub file created by `adb keygen`.

Run this only if you want to rotate the client key. After rotating you must
re-authorize the key on every Android device (the RSA fingerprint dialog).
"""

import base64
import struct
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

MODULUS_BYTES = 256  # 2048-bit RSA
COMMENT = b" adbhelper@ios\0"


def adb_public_key(private_key) -> bytes:
    numbers = private_key.private_numbers().public_numbers
    r32 = 1 << 32
    n0inv = (r32 - pow(numbers.n % r32, -1, r32)) % r32
    rr = pow(2, MODULUS_BYTES * 8 * 2, numbers.n)
    blob = struct.pack(
        "<LL256s256sL",
        MODULUS_BYTES // 4,
        n0inv,
        numbers.n.to_bytes(MODULUS_BYTES, "little"),
        rr.to_bytes(MODULUS_BYTES, "little"),
        numbers.e,
    )
    return base64.b64encode(blob) + COMMENT


def main() -> None:
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    private_der = key.private_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PrivateFormat.TraditionalOpenSSL,
        encryption_algorithm=serialization.NoEncryption(),
    )
    public = adb_public_key(key)
    # Keep the trailing NUL required by adb, but write it as a Swift escape
    # sequence instead of a literal NUL byte in the source file.
    public_swift = public.decode("utf-8").replace("\x00", "\\0")

    out = Path(__file__).resolve().parents[1] / "ADBHelper" / "AdbKeyData.swift"
    out.write_text(
        "// Generated by scripts/gen_adb_key.py — do not edit by hand.\n"
        "// Rotate with: python3 scripts/gen_adb_key.py\n"
        "enum AdbKeyData {\n"
        f'    static let privateKeyBase64 = "{base64.b64encode(private_der).decode()}"\n'
        f'    static let publicKeyBase64 = "{public_swift}"\n'
        "}\n",
        encoding="utf-8",
    )
    print(f"Wrote {out}")
    print(f"Public key fingerprint (SHA256): {base64.b64encode(__import__('hashlib').sha256(public).digest()).decode()}")


if __name__ == "__main__":
    main()
